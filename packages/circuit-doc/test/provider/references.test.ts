/**
 * The CAD reference contract (issue #15 / ADR-012): the exact-package gate is
 * a project-owned `selection.expect.packages` lock where 0 is a valid,
 * reviewed value; `cad.enabled` is a capability flag that must be respected
 * rather than silently skipped; and every containment/size/VRML safety check
 * upstream had keeps working, parameterised instead of hard-coded.
 */

